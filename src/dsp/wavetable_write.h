// xerum::dsp — the wavetable writer (ticket 34).
//
// Ticket 24 *reads* the reference's table format; this *writes* it. The two are deliberately separate
// files: a writer that shares its assumptions with its own reader proves nothing, so the round-trip test
// encodes here and decodes through ticket 24's `parseWavetable`.
//
// The format, as ticket 02 decoded it from the shipped corpus:
//
//   * RIFF/WAVE, little-endian, mono, 44100 Hz.
//   * `fmt ` is IEEE float32 (format tag 3, 32 bits) or 16-bit PCM (tag 1, 16 bits).
//   * `clm ` is the Xfer "cycle-length marker", an ASCII string NUL-padded to the chunk size:
//
//         <!>2048 BC000000 wavetable (...)
//
//     The number is the frame size (2048 throughout the factory corpus), `B` is the frame-interpolation
//     mode (0 none, 1 linear crossfade, 2/3/4 spectral morph) and `C` is the "Serum factory table" flag;
//     six zero nibbles follow. Ticket 24 reads both back as `FrameInterpolation` and `factory`.
//   * `data` is frame-major — frame f, sample i at `f * frameSize + i` — and the frame *count* is not
//     stored: it is computed from the data length, so nothing here may pad or truncate the payload.
//
// Two deliberate departures from the reference's own writer:
//
//   * **We do not reproduce its 16-bit size bug.** Its fourteen 16-bit tables declare `data` with the
//     32-bit byte count — twice the bytes present — and inflate the RIFF size to match. Ticket 24's
//     reader accepts exactly that arithmetic so those files still load; ours declares the true length,
//     and the test asserts both that ours is correct and that the inflated form is still readable.
//   * **The `clm ` vendor string is ours** ("wavetable (xerum)"), never Xfer's. Nothing xerum ships may
//     be byte-identical to a reference file, and the release check proves it
//     (`tools/check-content-provenance.py`).
//
// The formula evaluator is an **authoring-time** facility, not a plugin feature: it exists so the
// offline tool (`tools/wavetable-author.cpp`) can turn a written-down formula into samples
// (docs/content-policy.md). It is pure like the rest of this layer — no JUCE, no filesystem, never
// throws — and nothing on the audio path calls it. We implement the *idea* of a wavetable formula and
// ship formulas we wrote; the reference's factory formula list is content and is not reproduced.

#pragma once

#include "wavetable.h"

#include <cstddef>
#include <cstdint>
#include <memory>
#include <string>
#include <string_view>
#include <vector>

namespace xerum::dsp
{

// ---------------------------------------------------------------------------- the formula language

/// Names bound while a formula is evaluated. A frame is generated by evaluating one expression once per
/// sample:
///
///   `x`  time within the frame, −1 … 1      `n`  frame index, 0 … M−1
///   `w`  time within the frame, 0 … 1       `y`  frame position, 0 … 1
///   `i`  sample index, 0 … N−1              `z`  frame position, −1 … 1
///   `N`  frame size (samples per frame)     `M`  number of frames
///
/// Operators, tightest last: `?:` ternary, `||`, `&&`, `== != <= >= < >`, `+ -`, `* / %`, unary `- + !`,
/// and `^` (right-associative, as in the reference's grammar). Functions: sin cos tan asin acos atan
/// atan2 sinh cosh tanh asinh acosh atanh log ln log2 log10 exp sqrt cbrt abs sign rint floor ceil
/// round trunc frac step min max sum avg pow clamp. Constants: `pi`, `e`. `min`/`max`/`sum`/`avg` are
/// variadic; everything else has a fixed arity, checked at compile time so a typo is an authoring error
/// rather than a silent 0.
struct FormulaContext
{
    double x { 0.0 };
    double w { 0.0 };
    double i { 0.0 };
    double n { 0.0 };
    double y { 0.0 };
    double z { 0.0 };
    double N { 0.0 };
    double M { 0.0 };
};

/// A compiled formula. Compilation never throws; a failure is reported through `valid()` and `error()`.
class Formula
{
public:
    Formula() = default;

    static Formula fromText (std::string_view text);

    bool valid() const noexcept { return program_ != nullptr; }
    const std::string& error() const noexcept { return error_; }

    /// Evaluate a valid program. An invalid program evaluates to 0.
    double evaluate (const FormulaContext& context) const noexcept;

private:
    struct Program;
    std::shared_ptr<const Program> program_;
    std::string error_;
};

struct FormulaResult
{
    bool ok { false };
    double value { 0.0 };
    std::string error;
};

/// Compile-and-evaluate in one call, for tests and for one-off authoring checks.
FormulaResult evaluateFormula (std::string_view text, const FormulaContext& context);

// ---------------------------------------------------------------------------- the shipped library

/// One shipped table: the content, and how it was made. `formula` is the provenance of the samples —
/// the tool evaluates it, and the test suite re-evaluates it and asserts the shipped bytes are exactly
/// what it produces, so what ships is what the tool generated (docs/content-policy.md).
struct TableSpec
{
    std::string name;          ///< display name, e.g. "Sine"
    std::string relativePath;  ///< path under a content root's `Tables/`, e.g. "xerum/Sine.wav"
    std::string formula;       ///< our formula language, evaluated once per sample
    std::string description;   ///< one line, written to the provenance manifest
    std::size_t frameCount { 1 };
    FrameInterpolation interpolation { FrameInterpolation::None };
    std::uint8_t spectralSubMode { 2 };   ///< the `clm ` digit, used only for SpectralMorph
    bool sixteenBit { false };
    bool fallback { false };   ///< this is the table a caller substitutes when a reference misses
    double sampleRate { 44100.0 };
};

/// The starter library, in shipping order. Every entry is authored by us: basic shapes, which are
/// mathematics, and tables generated from formulas we wrote.
const std::vector<TableSpec>& starterLibrary();

/// The fallback table's reference as a preset would spell it, relative to a content root's `Tables/`.
/// It is *ours*, not the reference's "S2 Tables/Default Shapes.wav". Substituting it stays the caller's
/// decision and is reported, never silent: `content::TableLibrary` still reports a miss as a miss.
std::string_view fallbackTableReference();

/// Build the table a spec describes. Returns false with `error` set when the formula does not compile or
/// the spec is malformed; never throws.
bool buildTable (const TableSpec& spec, Wavetable& table, std::string& error);

// ---------------------------------------------------------------------------- encoding

struct EncodeOptions
{
    bool sixteenBit { false };
    FrameInterpolation interpolation { FrameInterpolation::None };
    std::uint8_t spectralSubMode { 2 };   ///< the digit written for SpectralMorph: 2, 3 or 4
    bool factory { false };
    double sampleRate { 44100.0 };
};

struct EncodeResult
{
    bool ok { false };
    std::string error;
    std::vector<std::byte> bytes;
};

/// Encode a table as RIFF/WAVE with `fmt `, `clm ` and `data`, every size declared truthfully. Never
/// throws; a malformed table is an error, not a crash.
EncodeResult encodeWavetable (const Wavetable& table, const EncodeOptions& options);

/// The options that reproduce a spec's on-disk form.
EncodeOptions encodeOptionsFor (const TableSpec& spec);

} // namespace xerum::dsp
