// The offline factory-bank authoring tool (ticket 54).
//
// xerum ships only content we author, and content is added *through* a tool so that what ships is what
// the tool generated rather than whatever happened to be in a working directory (docs/content-policy.md).
// This tool turns the bank in `src/presets/factory_bank.cpp` into the files a browser reads:
//
//     content/Factory/<Category>/<Name>.xerumpreset      one preset, in xerum's own block format
//     content/Factory/manifest.json                      every preset's name, category and contents
//
// and it refuses to write anything a preset cannot actually play:
//
//   * the bank's own vocabulary check must be empty (`presets::bankProblems()` — a warp mode, filter
//     type, noise colour, sub shape or matrix source the engine does not build is a preset whose module
//     silently does nothing, so it is an error here rather than a surprise in a session);
//   * every table a preset names must be one `dsp::starterLibrary()` generates **and** a file this
//     repository ships — a preset that pointed at `/Analog/Basic Shapes.wav` would be a preset the bank
//     could not legally travel with;
//   * every frame position must be inside the table it reads.
//
// `--verify` re-encodes every preset in memory and refuses to pass unless the bytes on disk are exactly
// what the bank describes, so the tree cannot drift from its source.
//
//     xerum-preset-author --out content --write --manifest content/Factory/manifest.json
//     xerum-preset-author --verify
//     xerum-preset-author --list

